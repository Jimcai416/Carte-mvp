// ---- tiny reactive store ----
let current = "English";
const listeners = new Set<() => void>();

export function getLanguage(): string {
  return current;
}

export function getLanguageLabel(): string {
  return LANGUAGES.find((l) => l.code === current)?.label ?? current;
}

export function setLanguage(code: string): void {
  current = code;
  AsyncStorage.setItem(LANG_KEY, code).catch(() => {});
  listeners.forEach((l) => l());
}

export async function initLanguage(): Promise<void> {
  try {
    const saved = await AsyncStorage.getItem(LANG_KEY);
    if (saved && STRINGS[saved]) {
      current = saved;
      listeners.forEach((l) => l());
    }
  } catch {}
}

export function useT(): (key: keyof typeof EN) => string {
  const [, force] = useReducer((x: number) => x + 1, 0);
  useEffect(() => {
    listeners.add(force);
    return () => {
      listeners.delete(force);
    };
  }, []);
  return (key) => STRINGS[current]?.[key] ?? EN[key] ?? String(key);
}
